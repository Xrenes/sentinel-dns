"""Text of the BIND files Sentinel manages (docs/BIND_INTEGRATION.md section 3). Pure functions, no I/O.

Every value comes from validated input, but is normalised again here (ipaddress, a strict hostname
pattern) so nothing can ever break out of a statement in named.conf or the response-policy zone.
"""
from __future__ import annotations

import ipaddress
import re
import sqlite3
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from typing import Any
from urllib.parse import urlsplit

from ..catalog import FEED_CATEGORIES
from ..config import BindLayout, Config
from ..policy import candidate_names, is_local
from ..repositories import policies
from ..validators import normalize_domain
from ..zonefile import ZoneMeta, soa_rdata

HEADER = "// Generated by Sentinel DNS from its database - change it with the dashboard or dnsctl.\n"
POLICY_NAME = "sentinel"
RPZ_TTL = 300
_HOSTNAME = re.compile(r"[a-z0-9_](?:[a-z0-9_-]{0,62})(?:\.[a-z0-9_](?:[a-z0-9_-]{0,62}))+")


@dataclass(frozen=True)
class RpzEntries:
    blocked: tuple[str, ...]
    allowed: tuple[str, ...]


def _lines(items: Iterable[str], indent: str = "    ") -> str:
    return "\n".join(f"{indent}{item};" for item in items)


def _networks(values: Iterable[object]) -> list[str]:
    return [str(ipaddress.ip_network(str(value).strip(), strict=False)) for value in values]


def _addresses(values: Iterable[object]) -> list[str]:
    return [str(ipaddress.ip_address(str(value).strip())) for value in values]


def _stats_endpoint(url: str) -> tuple[str, int]:
    parts = urlsplit(url)
    return str(ipaddress.ip_address(parts.hostname or "")), int(parts.port or 80)


def _listen(port: int) -> str:
    if port == 53:
        return ""
    return f"    listen-on port {port} {{ any; }};\n    listen-on-v6 port {port} {{ any; }};\n"


def _options_block(settings: Mapping[str, Any], layout: BindLayout) -> str:
    forwarders = " ".join(f"{address};" for address in _addresses(settings["forwarders"]))
    return (
        "options {\n"
        f'    directory "{layout.cache_dir.as_posix()}";\n'
        f"{_listen(layout.port)}"
        "    recursion yes;\n"
        "    allow-recursion { trusted; };\n"
        "    allow-query-cache { trusted; };\n"
        "    allow-query { any; };\n"
        "    allow-transfer { none; };\n"
        f"    forwarders {{ {forwarders} }};\n"
        "    forward first;\n"
        "    dnssec-validation auto;\n"
        "    querylog yes;\n"
        "    version none;\n"
        "    hostname none;\n"
        "    server-id none;\n"
        "    rate-limit {\n"
        f"        responses-per-second {int(settings['rrl_rps'])};\n"
        "        window 5;\n"
        "        exempt-clients { 127.0.0.1; ::1; };\n"
        "    };\n"
        # rules and ML detections first (their allow rules win), then the large feeds zone;
        # min-update-interval: apply firewall changes within seconds (BIND's default batches them for 60 s)
        f'    response-policy {{ zone "{normalize_domain(layout.rpz_zone)}"; '
        f'zone "{normalize_domain(layout.rpz_feeds_zone)}"; }} qname-wait-recurse no min-update-interval 5;\n'
        "};\n"
    )


def _logging_block(layout: BindLayout) -> str:
    return (
        "logging {\n"
        "    channel sentinel_queries {\n"
        f'        file "{layout.log_file.as_posix()}" versions 5 size 50m;\n'
        "        severity info;\n"
        "        print-time yes;\n"
        "        print-category yes;\n"
        "        print-severity yes;\n"
        "    };\n"
        "    category queries { sentinel_queries; };\n"
        "    category rpz { sentinel_queries; };\n"
        "    category lame-servers { null; };\n"
        "};\n"
    )


def render_options(settings: Mapping[str, Any], layout: BindLayout) -> str:
    """options.conf: ACL, resolver options, response policy, statistics channel and query logging."""
    local = ["127.0.0.1", "::1"]
    trusted = local + [network for network in _networks(settings["acl"]) if network not in ("127.0.0.1/32", "::1/128")]
    host, port = _stats_endpoint(layout.stats_url)
    return (
        f"{HEADER}\n"
        f'acl "trusted" {{\n{_lines(trusted)}\n}};\n\n'
        f"{_options_block(settings, layout)}\n"
        f"statistics-channels {{\n    inet {host} port {port} allow {{ 127.0.0.1; }};\n}};\n\n"
        f"{_logging_block(layout)}"
    )


def _zone_statement(name: str, path: str, extra: Iterable[str]) -> str:
    body = _lines(["type primary", f'file "{path}"', *extra, "allow-transfer { none; }"])
    return f'zone "{name}" {{\n{body}\n}};\n'


def render_zones(cfg: Config) -> str:
    """zones.conf: the DNSSEC policy (separate KSK and ZSK), the two lab zones and the two response-policy zones."""
    layout = cfg.bind
    forward, reverse, rpz, feeds = (normalize_domain(name) for name in
                                    (cfg.zone, cfg.reverse_zone, layout.rpz_zone, layout.rpz_feeds_zone))
    policy = (
        f'dnssec-policy "{POLICY_NAME}" {{\n'
        "    keys {\n"
        "        ksk lifetime unlimited algorithm ecdsap256sha256;\n"
        "        zsk lifetime P90D algorithm ecdsap256sha256;\n"
        "    };\n"
        "    signatures-refresh P5D;\n"
        "    signatures-validity P14D;\n"
        "    signatures-validity-dnskey P14D;\n"
        "};\n"
    )
    signing = [f'dnssec-policy "{POLICY_NAME}"', "inline-signing yes", f'key-directory "{layout.key_dir.as_posix()}"']
    return "\n".join((
        HEADER, policy,
        _zone_statement(forward, layout.zone_path(forward).as_posix(), signing),
        _zone_statement(reverse, layout.zone_path(reverse).as_posix(), []),
        _zone_statement(rpz, layout.zone_path(rpz).as_posix(), ["allow-query { localhost; }"]),
        _zone_statement(feeds, layout.zone_path(feeds).as_posix(), ["allow-query { localhost; }"]),
    ))


def rpz_entries(conn: sqlite3.Connection) -> RpzEntries:
    """The rules zone: administrator rules and ML detections, as dnscore.policy.evaluate decides them.

    Allow rules win and local zones are skipped. Downloaded feeds live in the feeds zone (feed_entries),
    which BIND consults after this one, so an allow rule here also overrides the feeds.
    """
    snapshot = policies.load_snapshot(conn)
    zones = snapshot.local_zones
    allowed = {name for name in snapshot.allow_rules if not is_local(name, zones)}
    detected = {name for name, category in snapshot.blocklist.items() if category == "ml" and "ml" in snapshot.enabled}
    blocked = {
        name for name in detected | set(snapshot.block_rules)
        if not is_local(name, zones) and not allowed.intersection(candidate_names(name))
    }
    return RpzEntries(blocked=tuple(sorted(blocked)), allowed=tuple(sorted(allowed)))


def feed_entries(conn: sqlite3.Connection) -> RpzEntries:
    """The feeds zone: names of the enabled feed categories, minus local names and names a listed parent covers."""
    snapshot = policies.load_snapshot(conn)
    zones = snapshot.local_zones
    listed = {name for name, category in snapshot.blocklist.items()
              if category in FEED_CATEGORIES and category in snapshot.enabled and not is_local(name, zones)}
    blocked = {name for name in listed if listed.isdisjoint(candidate_names(name)[1:])}
    return RpzEntries(blocked=tuple(sorted(blocked)), allowed=())


def _rpz_line(owner: str, target: str) -> str:
    return f"{owner:<40} CNAME {target}"


def render_rpz(entries: RpzEntries, *, serial: int, forward_zone: str) -> str:
    """Response-policy zone: NXDOMAIN for blocked names and their subdomains, passthru for allow rules."""
    meta = ZoneMeta.for_zone("rpz", serial, forward_zone)
    blocked = [name for name in entries.blocked if _HOSTNAME.fullmatch(name)]
    allowed = [name for name in entries.allowed if _HOSTNAME.fullmatch(name)]
    lines = [
        f"$TTL {RPZ_TTL}",
        f"@ IN SOA {soa_rdata(meta)}",
        "@ IN NS localhost.",
        f"; {len(blocked)} blocked names, {len(allowed)} allow rules",
    ]
    for name in blocked:
        lines += [_rpz_line(name, "."), _rpz_line(f"*.{name}", ".")]
    for name in allowed:
        lines += [_rpz_line(name, "rpz-passthru."), _rpz_line(f"*.{name}", "rpz-passthru.")]
    return "\n".join(lines) + "\n"
