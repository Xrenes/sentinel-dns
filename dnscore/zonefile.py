"""Render BIND zone files from database records (pure functions, no I/O)."""
from __future__ import annotations

import re
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from datetime import date

SOA_TIMERS = (
    ("refresh", 3600),
    ("retry", 900),
    ("expire", 1_209_600),
    ("negative cache TTL", 300),
)
TYPE_ORDER = ("SOA", "NS", "A", "AAAA", "CNAME", "MX", "TXT", "PTR")
TXT_CHUNK = 255
SOA_INDENT = " " * 40
_CONTROL = re.compile(r"[\x00-\x1f\x7f]")


@dataclass(frozen=True)
class ZoneMeta:
    name: str
    serial: int
    primary_ns: str
    hostmaster: str
    default_ttl: int = 3600

    @classmethod
    def for_zone(cls, name: str, serial: int, forward_zone: str) -> ZoneMeta:
        """Every zone (forward and reverse) is served by ns1 of the forward zone."""
        return cls(name=name, serial=serial, primary_ns=f"ns1.{forward_zone}.",
                   hostmaster=f"hostmaster.{forward_zone}.")


def soa_rdata(meta: ZoneMeta) -> str:
    """Single-line SOA RDATA, e.g. for a synthesized SOA answer."""
    timers = " ".join(str(value) for _, value in SOA_TIMERS)
    return f"{meta.primary_ns} {meta.hostmaster} {meta.serial} {timers}"


def next_serial(current: int, today: date) -> int:
    """Date-based serial (YYYYMMDDnn) that always increases."""
    base = int(today.strftime("%Y%m%d")) * 100
    return current + 1 if current >= base else base + 1


def _quote_txt(text: str) -> str:
    """Split into 255-character strings (RFC 1035) and escape backslashes and quotes."""
    chunks = [text[i : i + TXT_CHUNK] for i in range(0, len(text), TXT_CHUNK)] or [""]
    escaped = (chunk.replace("\\", "\\\\").replace('"', '\\"') for chunk in chunks)
    return " ".join(f'"{chunk}"' for chunk in escaped)


def _rdata(record: Mapping) -> str:
    if record["type"] == "MX":
        return f"{record['priority']} {record['value']}"
    if record["type"] == "TXT":
        return _quote_txt(str(record["value"]))
    return str(record["value"])


def _safe(text: str) -> str:
    """Defense in depth: validated data never contains control characters, so refuse them."""
    if _CONTROL.search(text):
        raise ValueError(f"Refusing to write control characters into a zone file: {text!r}")
    return text


def _line(name: str, ttl: int | str, rtype: str, rdata: str) -> str:
    # Fixed-width columns, but always at least one space so long owner names stay separate.
    return f"{_safe(name):<23} {ttl!s:<7} IN  {rtype:<6} {_safe(rdata)}"


def _name_key(name: str) -> tuple:
    return tuple((0, int(part), "") if part.isdigit() else (1, 0, part) for part in name.split("."))


def _sort_key(record: Mapping) -> tuple:
    rtype = record["type"]
    order = TYPE_ORDER.index(rtype) if rtype in TYPE_ORDER else len(TYPE_ORDER)
    return (record["name"] != "@", _name_key(record["name"]), order, str(record["value"]))


def render_zone(meta: ZoneMeta, records: Iterable[Mapping]) -> str:
    items = sorted(records, key=_sort_key)
    soa_values = [(meta.serial, "serial"), *((value, label) for label, value in SOA_TIMERS)]
    lines = [
        f"; Zone file for {meta.name}",
        "; Generated by Sentinel DNS from the dashboard database - manual edits will be overwritten.",
        f"$ORIGIN {meta.name}.",
        f"$TTL {meta.default_ttl}",
        _line("@", "", "SOA", f"{meta.primary_ns} {meta.hostmaster} ("),
        *(f"{SOA_INDENT}{value!s:<12}; {label}" for value, label in soa_values),
        f"{SOA_INDENT})",
        "",
    ]
    if not any(r["type"] == "NS" and r["name"] == "@" for r in items):
        lines.append(_line("@", meta.default_ttl, "NS", meta.primary_ns))
    lines.extend(_line(r["name"], r["ttl"], r["type"], _rdata(r)) for r in items)
    return "\n".join(lines) + "\n"
